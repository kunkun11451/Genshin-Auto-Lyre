// ============================================================
// 黑键半音偏移集合
// 在一个八度内（0~11），以下半音位置为黑键：
//   1=C#, 3=D#, 6=F#, 8=G#, 10=A#
// ============================================================
export const BLACK_KEY_SEMITONES: ReadonlySet<number> = new Set([1, 3, 6, 8, 10]);

// ============================================================
// 黑键映射表 —— 用于不同黑键处理策略
// 键: 八度内的半音偏移（黑键位置）
// 值: 映射到的白键半音偏移
// ============================================================

/** floor 策略：黑键向下（左侧）映射到最近的白键 */
export const FLOOR_MAP: Readonly<Record<number, number>> = {
  1: 0,   // C# → C
  3: 2,   // D# → D
  6: 5,   // F# → F
  8: 7,   // G# → G
  10: 9,  // A# → A
};

/** ceil 策略：黑键向上（右侧）映射到最近的白键 */
export const CEIL_MAP: Readonly<Record<number, number>> = {
  1: 2,   // C# → D
  3: 4,   // D# → E
  6: 7,   // F# → G
  8: 9,   // G# → A
  10: 11, // A# → B
};

/** nearest 策略：黑键就近映射（偏好方向固定） */
export const NEAREST_MAP: Readonly<Record<number, number>> = {
  1: 0,   // C# → C（向下）
  3: 4,   // D# → E（向上）
  6: 7,   // F# → G（向上）
  8: 9,   // G# → A（向上）
  10: 11, // A# → B（向上）
};

